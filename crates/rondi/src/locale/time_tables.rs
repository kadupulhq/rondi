//! The 21 tables from `TIME_CS_CZ` onward were generated from the Unicode
//! CLDR JSON release tagged `49.0.0` (<https://github.com/unicode-org/cldr-json>),
//! reading `cldr-json/cldr-dates-full/main/<cldr-id>/ca-gregorian.json` for
//! each locale. Month and weekday names come from the `stand-alone` `wide`
//! and `abbreviated` contexts, `%p` from `dayPeriods.format.abbreviated`,
//! `%x` from `dateFormats.short` (year widened to `%Y`), `%X` from
//! `timeFormats.medium`, and `%c` joins `%a %d %b %Y` to `%X` with the
//! separator of `dateTimeFormats.medium`. Numeric fields are always
//! zero-padded and U+202F in patterns becomes an ASCII space, matching the
//! older tables. `%r` uses `%X` when that is a 12-hour pattern and
//! `%I:%M:%S %p` otherwise.

